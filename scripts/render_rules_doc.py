"""Render `docs/RULES.md` (every rule with its citations) and `docs/VIOLATION_TYPES.md` (the
violation types the service reports, task.md §8) from the runtime Knowledge Pack. Re-run after
`scripts/build_knowledge.py`:

    .venv/bin/python scripts/render_rules_doc.py

`tests/test_knowledge.py` asserts both committed files match this script's output.
"""

from __future__ import annotations

from pathlib import Path

from backend.knowledge import Knowledge

ROOT = Path(__file__).resolve().parent.parent
KNOWLEDGE_DIR = ROOT / "knowledge"
OUT = ROOT / "docs" / "RULES.md"
TYPES_OUT = ROOT / "docs" / "VIOLATION_TYPES.md"


def render(knowledge: Knowledge) -> str:
    lines = [
        "# Rules",
        "",
        "Generated by `scripts/render_rules_doc.py` from `knowledge/rules.yaml` and "
        "`knowledge/norms.json`. Do not edit by hand -- edit the Knowledge Pack and re-render.",
        "",
    ]
    for rule in knowledge.rules:
        status = "enabled" if rule.enabled else "disabled"
        lines.append(f"## {rule.rule_id} ({status})")
        lines.append("")
        lines.append(
            f"- **Business status**: {rule.business_status}; **implementation**: "
            f"{rule.implementation_status}"
        )
        if rule.disabled_reason:
            lines.append(f"- **Disabled reason**: {rule.disabled_reason}")
        lines.append(f"- **Jury-eligible**: {'yes' if rule.jury_eligible else 'no'}")
        lines.append(f"- **RU**: {rule.title_ru}")
        lines.append(f"- **EN**: {rule.title_en}")
        lines.append(f"- **Mechanism**: {rule.mechanism}")
        lines.append(f"- **States used**: {', '.join(rule.states_used)}")
        lines.append(f"- **What the video cannot establish**: {rule.visibility_caveat}")
        lines.append("- **Norms**:")
        for norm_id in rule.norm_ids:
            norm = knowledge.norm(norm_id)
            status_txt = norm.citation_status
            primary = " (primary)" if norm_id == rule.norm_ids[0] else ""
            lines.append(
                f"  - `{norm.norm_id}`{primary}: {norm.jurisdiction}, {norm.document_title}, "
                f"{norm.issuing_authority}, № {norm.act_number} ({norm.adopted_on}), "
                f"{norm.punkt} -- [{status_txt}]({norm.url}) -- relationship: "
                f"{rule.citation_strengths[norm_id]}"
            )
            lines.append(f"    > {norm.quote}")
        lines.append("")
    return "\n".join(lines).rstrip() + "\n"


def _type_line(knowledge: Knowledge, rule) -> str:
    line = f"- **{rule.title_ru}** (`{rule.rule_id}`) -- {rule.title_en}."
    if rule.norm_ids:
        norm = knowledge.norm(rule.norm_ids[0])
        line += f" Основание: постановление № {norm.act_number}, {norm.punkt}."
    return line


def render_types(knowledge: Knowledge) -> str:
    reported = [r for r in knowledge.rules if r.jury_eligible]
    pending = [r for r in knowledge.rules if r.enabled and not r.jury_eligible]
    off = [r for r in knowledge.rules if not r.enabled]
    lines = [
        "# Violation types",
        "",
        "Generated by `scripts/render_rules_doc.py` from the Knowledge Pack, which is generated "
        "from `knowledge/rulebook.yaml`. Do not edit by hand.",
        "",
        "task.md §8 asks for the list of violation types the solution recognises. The organizers "
        "publish no closed list (FAQ 8-9), so this is the service's own list. The API's `type` "
        "for a violation is always one of these Russian names, never free text. Full citations: "
        "[`RULES.md`](RULES.md).",
        "",
        "## Reported to the jury",
        "",
        "Detected, and every cited norm verified by a person on adilet.zan.kz (`RULE_SCOPE=jury`).",
        "",
        *(
            [_type_line(knowledge, r) for r in reported]
            or ["None yet: no rule's legal basis is verified."]
        ),
        "",
        "## Detected, legal basis pending verification",
        "",
        "Reported only with `RULE_SCOPE=detector` (experiments), with citations marked pending.",
        "",
        *([_type_line(knowledge, r) for r in pending] or ["None."]),
        "",
        "## Not detected",
        "",
        *([f"- `{r.rule_id}` ({r.title_ru}): {r.disabled_reason}" for r in off] or ["None."]),
    ]
    return "\n".join(lines).rstrip() + "\n"


def main() -> None:
    knowledge = Knowledge.load(KNOWLEDGE_DIR)
    OUT.parent.mkdir(parents=True, exist_ok=True)
    for path, text in ((OUT, render(knowledge)), (TYPES_OUT, render_types(knowledge))):
        path.write_text(text, encoding="utf-8")
        print(f"wrote {path}")


if __name__ == "__main__":
    main()
