"""Export serialized Pydantic response types for the TypeScript client."""

import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))

from backend.models import AcceptedJob, DoneJob, FailedJob, ProcessingJob  # noqa: E402


def ts_type(schema: dict) -> str:
    if "$ref" in schema:
        return schema["$ref"].rsplit("/", 1)[1]
    if "const" in schema:
        return repr(schema["const"])
    if "enum" in schema:
        return " | ".join(repr(value) for value in schema["enum"])
    if "anyOf" in schema:
        return " | ".join(dict.fromkeys(ts_type(value) for value in schema["anyOf"]))
    kind = schema.get("type")
    if kind == "array":
        return f"Array<{ts_type(schema['items'])}>"
    if kind == "object":
        if "properties" in schema:
            return (
                "{\n"
                + "".join(
                    f"  {name}: {ts_type(value)};\n" for name, value in schema["properties"].items()
                )
                + "}"
            )
        return f"Record<string, {ts_type(schema['additionalProperties'])}>"
    return {
        "string": "string",
        "number": "number",
        "integer": "number",
        "boolean": "boolean",
        "null": "null",
    }[kind]


def contract_text() -> str:
    definitions = {}
    for model in (AcceptedJob, ProcessingJob, FailedJob, DoneJob):
        schema = model.model_json_schema(mode="serialization")
        definitions.update(schema.pop("$defs", {}))
        definitions[model.__name__] = schema
    return (
        "// Generated by scripts/export_contract.py; do not edit.\n"
        + "\n".join(
            f"export type {name} = {ts_type(schema)};" for name, schema in definitions.items()
        )
        + "\nexport type Job = ProcessingJob | FailedJob | DoneJob;\n"
    )


if __name__ == "__main__":
    destination = Path(__file__).resolve().parents[1] / "frontend/src/contract.ts"
    destination.parent.mkdir(parents=True, exist_ok=True)
    destination.write_text(contract_text(), encoding="utf-8")
